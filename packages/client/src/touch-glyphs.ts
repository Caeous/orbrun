export type TouchGlyph = keyof typeof GLYPHS

export function isTouchGlyph(s: string): s is TouchGlyph {
  return Object.hasOwn(GLYPHS, s)
}

/** A glyph as an SVG path on the 26-pixel square: each run of squares in a row, one rectangle. */
export function glyphPath(name: TouchGlyph): string {
  let d = ''
  GLYPHS[name].forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== '#') {
        x++
        continue
      }
      let w = 0
      while (row[x + w] === '#') w++
      d += `M${x * 2} ${y * 2}h${w * 2}v2h${-w * 2}z`
      x += w
    }
  })
  return d
}

